// Sweep all episode MDXes for the "Ashley-as-protagonist" summary pattern
// — Haiku's bias toward describing the host as the one doing the thing
// (e.g. "Ashley explores X" or "Ashley journeys to Y"), when in fact
// Ashley is the host and the guest is the one with the perspective.
//
// Reports flagged episodes to docs/ashley-protagonist-sweep.md so the
// next reviewer can rewrite each summary in guest-centric voice.

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import yaml from 'js-yaml';

const EPISODES_DIR = 'src/content/episodes';

// Patterns where Ashley is being narrated as the protagonist of a journey
// or analysis. NOT triggered by neutral mentions like "Ashley sits down
// with Geoffrey Long to discuss…" (Ashley is host-as-interviewer there).
const ASHLEY_PROTAGONIST = /^Ashley\s+(?:explores|examines|argues|describes|journeys|investigates|reflects|analyzes|critiques|interviews|reckons|wrestles|grapples|surveys|maps|delves|unpacks|reframes|considers|reads|navigates|takes\s+on|takes\s+up)/i;

function splitFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) return null;
  return { fm: m[1], body: m[2] };
}

const flagged = [];
let total = 0;
for (const f of readdirSync(EPISODES_DIR).filter((f) => f.endsWith('.mdx'))) {
  const text = readFileSync(join(EPISODES_DIR, f), 'utf8');
  const parts = splitFrontmatter(text);
  if (!parts) continue;
  const fm = yaml.load(parts.fm);
  if (!fm.summary) continue;
  total++;
  const summary = String(fm.summary).trim();
  if (ASHLEY_PROTAGONIST.test(summary)) {
    flagged.push({
      number: fm.number,
      file: f,
      title: fm.title,
      guest: fm.guest || '(none)',
      draft: !!fm.draft,
      excerpt: summary.slice(0, 240),
    });
  }
}
flagged.sort((a, b) => Number(a.number) - Number(b.number));

mkdirSync('docs', { recursive: true });
const lines = [];
lines.push('# Ashley-as-protagonist sweep');
lines.push('');
lines.push(`Run: ${new Date().toISOString()}`);
lines.push('');
lines.push(`Scanned ${total} episodes. **Flagged ${flagged.length}** where the summary opens with "Ashley + active verb" — i.e. Haiku has narrated the host as the protagonist of the episode's journey or analysis. The right voice is guest-centric: the GUEST does the exploring / journeying / arguing; Ashley hosts.`);
lines.push('');
lines.push('| Ep # | File | Guest | Draft? | Summary opening |');
lines.push('|------|------|-------|--------|-----------------|');
for (const f of flagged) {
  lines.push(
    `| ${f.number} | \`${f.file}\` | ${f.guest} | ${f.draft ? '✓' : ' '} | ${f.excerpt.replace(/\|/g, '\\|')}… |`,
  );
}
lines.push('');
lines.push('## How to fix one');
lines.push('');
lines.push('1. Open the MDX file');
lines.push('2. Rewrite the `summary:` frontmatter field (and the matching `## Summary` body section) in guest-centric voice. Example: instead of *"Ashley explores the fracturing of the anti-AI movement"*, write *"A conversation with [guest] on the fracturing of the anti-AI movement"* or *"[Guest] traces the fracturing of the anti-AI movement…"*.');
lines.push('3. If you want this regenerated by Haiku from scratch, set `summary: "[Pending re-enrichment]"` and the `reenrich-episodes.yml` workflow will pick it up on next run.');

writeFileSync('docs/ashley-protagonist-sweep.md', lines.join('\n'));
console.log(`Scanned ${total}; flagged ${flagged.length}.`);
console.log(`Report: docs/ashley-protagonist-sweep.md`);
